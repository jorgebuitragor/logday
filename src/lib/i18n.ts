export function t<S extends SectionKey>(lang: Language, section: S, key: keyof Dict[S] & string): string;
export function t(lang: Language, sectionOrKey: string, subKey?: string): string {
  const d = dict[lang] ?? dict['es'];
  if (subKey) {
    const section = (d as unknown as Record<string, Record<string, string>>)[sectionOrKey];
    return section?.[subKey] ?? subKey;
  }
  return (d as unknown as Record<string, string>)[sectionOrKey] ?? sectionOrKey;
}
